/**
 * Same key structure as `en`, with values widened to `string`.
 *
 * Without the widening, `as const` would pin every value to its English
 * literal, and a translated locale could not satisfy the type.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };

export type ResourceShape = Widen<typeof en>;